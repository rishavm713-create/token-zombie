def main(argv):
    if argv and argv[0] == 'scaffold':
        argv = argv[1:]
    op = lambda k, d=None: argv[argv.index(k) + 1] if k in argv else d
    skip = {op('--dir'), op('--fields')}
    idea = ' '.join(a for a in argv if not a.startswith('--') and a not in skip)
    if not idea:
        print('usage: tz scaffold "<idea>" [--dir D] [--fields a,b,c]', file=sys.stderr); return 2
    t = entity(idea)
    fields = [f for f in re.findall(r'[a-z_]+', (op('--fields') or 'name,notes').lower())] or ['name']
    d = op('--dir') or t + '-saas'
    if os.path.exists(os.path.join(d, 'app.py')):
        print('refused: %s/app.py exists' % d, file=sys.stderr); return 3
    os.makedirs(d, exist_ok=True)
    sub = lambda s: s.replace('__T__', t).replace('__NAME__', d).replace('__FIELDS__', repr(fields)).replace('__F0__', fields[0])
    for name, body in (('app.py', APP), ('test_app.py', TEST),
                       ('README.md', '# %s\nGenerated by `tz scaffold` from: %s\n\nRun `python3 app.py` (port 8000). Test `python3 -m unittest -q`.\nAPI: POST /signup, POST /login, then GET/POST /%s, DELETE /%s/ID with `Authorization: Bearer TOKEN`.\n\nNot included: payments, email, HTML UI, hosting. Add them with `tz run --go`.\n' % (d, idea, t, t))):
        open(os.path.join(d, name), 'w').write(sub(body))
    print('scaffold: %s/ (resource /%s, fields %s). 0 tokens. test: cd %s && python3 -m unittest -q' % (d, t, ','.join(fields), d))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
