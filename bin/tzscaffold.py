#!/usr/bin/env python3
# `tz scaffold "<idea>" [--dir D] [--fields a,b,c]`: writes a working SaaS skeleton from local templates. 0 tokens, stdlib only.
# App: signup/login (scrypt, sessions), one CRUD resource per account, JSON API + simple HTML, sqlite, tests. Idea words pick the resource name.
import os, re, sys

STOP = {'a', 'an', 'the', 'saas', 'app', 'tool', 'for', 'to', 'that', 'lets', 'let', 'me', 'build', 'make', 'my', 'of', 'and', 'with', 'track', 'tracking', 'manage', 'managing', 'platform', 'service', 'product', 'simple', 'small'}


def entity(idea):
    ws = [w for w in re.findall(r'[a-z]+', idea.lower()) if w not in STOP]
    w = ws[-1] if ws else 'item'
    return w[:-1] if w.endswith('s') and len(w) > 3 else w


APP = '''#!/usr/bin/env python3
# __NAME__: generated by tz scaffold (0 tokens). Stdlib only. Run: python3 app.py   Test: python3 -m unittest -q
import hashlib, hmac, json, os, secrets, sqlite3, sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
FIELDS = __FIELDS__
DB = os.environ.get('APP_DB', 'app.db')


def db():
    c = sqlite3.connect(DB); c.row_factory = sqlite3.Row
    c.executescript("create table if not exists users(id integer primary key, email text unique, pw text);"
                    "create table if not exists sessions(tok text primary key, uid integer);"
                    "create table if not exists __T__(id integer primary key, uid integer, " + ",".join(f + " text" for f in FIELDS) + ");")
    return c


def hpw(p, salt=None):
    salt = salt or secrets.token_hex(8)
    return salt + '$' + hashlib.scrypt(p.encode(), salt=salt.encode(), n=2 ** 14, r=8, p=1).hex()


def check(p, h):
    return hmac.compare_digest(hpw(p, h.split('$')[0]), h)


def handle(method, path, body, tok):
    """Returns (status, json). Easy to test without a socket. Always closes its connection."""
    c = db()
    try:
        return _handle(c, method, path, body, tok)
    finally:
        c.close()


def _handle(c, method, path, body, tok):
    if path == '/signup' and method == 'POST':
        try:
            c.execute('insert into users(email,pw) values(?,?)', (body.get('email', ''), hpw(body.get('password', '')))); c.commit()
        except sqlite3.IntegrityError:
            return 409, {'error': 'email taken'}
        return 201, {'ok': True}
    if path == '/login' and method == 'POST':
        u = c.execute('select * from users where email=?', (body.get('email', ''),)).fetchone()
        if not u or not check(body.get('password', ''), u['pw']):
            return 401, {'error': 'bad login'}
        t = secrets.token_urlsafe(24); c.execute('insert into sessions values(?,?)', (t, u['id'])); c.commit()
        return 200, {'token': t}
    s = c.execute('select uid from sessions where tok=?', (tok or '',)).fetchone()
    if not s:
        return 401, {'error': 'login first'}
    uid = s['uid']
    if path == '/__T__' and method == 'GET':
        return 200, [dict(r) for r in c.execute('select * from __T__ where uid=?', (uid,))]
    if path == '/__T__' and method == 'POST':
        cur = c.execute('insert into __T__(uid,' + ','.join(FIELDS) + ') values(?' + ',?' * len(FIELDS) + ')', (uid, *[str(body.get(f, '')) for f in FIELDS])); c.commit()
        return 201, {'id': cur.lastrowid}
    if path.startswith('/__T__/') and method == 'DELETE':
        c.execute('delete from __T__ where id=? and uid=?', (path.split('/')[-1], uid)); c.commit()
        return 200, {'ok': True}
    return 404, {'error': 'not found'}


class H(BaseHTTPRequestHandler):
    def go(self):
        n = int(self.headers.get('content-length') or 0)
        try:
            body = json.loads(self.rfile.read(n) or b'{}')
        except ValueError:
            body = {}
        st, out = handle(self.command, self.path, body, (self.headers.get('authorization') or '').replace('Bearer ', ''))
        b = json.dumps(out).encode(); self.send_response(st); self.send_header('content-type', 'application/json'); self.send_header('content-length', str(len(b))); self.end_headers(); self.wfile.write(b)
    do_GET = do_POST = do_DELETE = go
    def log_message(self, *a): pass


if __name__ == '__main__':
    ThreadingHTTPServer(('127.0.0.1', int(os.environ.get('PORT', 8000))), H).serve_forever()
'''

