# tztips v2.1 tests (positive + false-positive controls, temp dirs only).
import os, json, time, tempfile
from harness import ok, done
import tztips as T
H = tempfile.mkdtemp(); CW = os.path.join(H, 'proj'); os.makedirs(CW); os.makedirs(os.path.join(H, '.claude'))
body = '# Rules\n' + ''.join('- rule number %d keep tokens low\n' % i for i in range(30)) + '# Steps\n' + ''.join('%d. do step %d of the long procedure here\n' % (i, i) for i in range(1, 60))
cm = os.path.join(H, '.claude', 'CLAUDE.md'); ag = os.path.join(H, 'AGENTS.md')
open(cm, 'w').write(body); open(ag, 'w').write(body + '- one extra line\n')
r = T.instr_report(H, CW)
f = {x['path']: x for x in r['files']}
ok('claude loaded', f[cm]['loaded'] and f[cm]['tokens_est'] > 0)
ok('agents not loaded, listed', ag in f and not f[ag]['loaded'])
ok('total counts loaded only', r['total_est'] == f[cm]['tokens_est'])
ok('agents duplicates claude', any({d['a'], d['b']} == {cm, ag} for d in r['duplicates']))
ok('big sections top3', 1 <= len(r['biggest_sections']) <= 3)
ok('skill candidate procedural', any(s['heading'] == 'Steps' for s in r['skill_candidates']))
ok('advice over threshold', 'tz instr --fix' in T.instr_advice(r, 10) and 'duplicate' in T.instr_advice(r, 10))
ok('advice under threshold silent', T.instr_advice(r, 10**6) == '')
# import: AGENTS imported -> loaded, both loaded -> fix plan
open(cm, 'w').write('@../AGENTS.md\n' + body)
r2 = T.instr_report(H, CW)
ok('imported AGENTS loaded', {x['path']: x['loaded'] for x in r2['files']}[ag])
bk = os.path.join(H, 'bk'); before = open(ag, 'rb').read()
plan0 = T.instr_fix(r2)
ok('fix dry run changes nothing', open(ag, 'rb').read() == before)
open(cm, 'w').write(body)  # not loaded AGENTS case
r3 = T.instr_report(H, CW)
ok('unloaded duplicate: no replace', all(a['action'] != 'replace' for a in T.instr_fix(r3)))
# both loaded: two CLAUDE.md files (home + cwd)
c2 = os.path.join(CW, 'CLAUDE.md'); open(c2, 'w').write(body)
r4 = T.instr_report(H, CW); b1, b2 = open(cm, 'rb').read(), open(c2, 'rb').read()
pl = T.instr_fix(r4)
ok('both loaded -> replace plan', any(a['action'] == 'replace' for a in pl))
ok('dry run untouched', open(c2, 'rb').read() == b2 and open(cm, 'rb').read() == b1)
pl = T.instr_fix(r4, apply=True, backup_dir=bk)
ok('apply wrote import', any(open(p, 'r').read().startswith('@') and len(open(p).read().splitlines()) == 1 for p in (cm, c2)))
ok('undo info present', any(a['action'] == 'undo-info' for a in pl))
ok('restore returns count', T.instr_restore(bk) == 1)
ok('round trip byte-identical', open(cm, 'rb').read() == b1 and open(c2, 'rb').read() == b2)
ok('report on missing dirs never raises', T.instr_report('/nonexistent', '/nonexistent')['total_est'] == 0)
# 2 model
ok('model mechanical', 'Sonnet/Haiku' in T.model_advice('rename variable foo to bar'))
ok('model typo', T.model_advice('fix the typo in readme') != '')
ok('model skipped on sonnet', T.model_advice('rename foo to bar', 'claude-sonnet-5') == '')
ok('model hard silent', T.model_advice('debug why the race condition happens, rename later') == '')
ok('model design silent', T.model_advice('design the architecture') == '')
ok('model long prompt silent', T.model_advice('rename ' + 'word ' * 40) == '')
ok('model plain silent', T.model_advice('what does this do') == '')
# 3 plan
ok('plan vague build', 'plan' in T.plan_advice('build me a full app for tracking invoices'))
ok('plan long vague', T.plan_advice(' '.join(['thing'] * 65)) != '')
ok('plan path specific silent', T.plan_advice('build the parser in bin/tzlib.py') == '')
ok('plan backticks silent', T.plan_advice('migrate `foo` to bar') == '')
ok('plan short plain silent', T.plan_advice('what is a closure') == '')
# 4 bulk
ok('bulk 8 reads', T.bulk_reads(['Read', 'Grep', 'Glob'] * 3))
ok('bulk edit breaks', not T.bulk_reads(['Read'] * 7 + ['Edit']))
ok('bulk bash breaks', not T.bulk_reads(['Read'] * 20 + ['Bash']))
ok('bulk too few', not T.bulk_reads(['Read'] * 3))
ok('bulk after edit counts from end', T.bulk_reads(['Edit'] + ['Read'] * 8))
mk = lambda n, side=False: json.dumps({'type': 'assistant', 'isSidechain': side, 'message': {'content': [{'type': 'tool_use', 'name': n}]}})
ok('bulk transcript lines', T.bulk_reads([mk('Read') for _ in range(8)]))
ok('bulk ignores sidechain Bash', T.bulk_reads([mk('Read') for _ in range(8)] + [mk('Bash', True)]))
ok('bulk n param', T.bulk_reads(['Read'] * 3, n=3))
m = T.bulk_block_msg()
ok('bulk msg', 'Explore' in m and 'TZ_FEAT_BULK_READ_BLOCK=0' in m and 'features.bulk_read_block' in m)
# 5 size
C = {'size_soft': [50000, 100000], 'size_cap': 150000}
ok('size ok', T.size_gate(10000, C) == ('ok', ''))
ok('soft50', T.size_gate(60000, C)[0] == 'soft50')
ok('soft100', T.size_gate(120000, C)[0] == 'soft100')
ok('block', T.size_gate(150000, C)[0] == 'block' and '/clear now' in T.size_gate(160000, C)[1])
ok('cap off', T.size_gate(900000, {'size_soft': [50000, 100000], 'size_cap': 0})[0] == 'soft100')
sm = T.size_gate(60000, C)[1]
ok('soft msg parts', all(s in sm for s in ('mcp__ccd_turn__wrap_up', 'Fresh chat', 'clear_session', '"self"', '`/clear`', 'tz handoff save')))
t0 = time.time(); p = T.save_handoff(CW, 'done: a\nleft: b', now=t0)
ok('handoff path', p.endswith(time.strftime('%Y-%m-%d', time.localtime(t0)) + '.md') and os.path.isfile(p))
T.save_handoff(CW, 'second note', now=t0 + 60)
txt = open(p).read()
ok('handoff append not clobber', 'done: a' in txt and 'second note' in txt)
for i in range(12):
    T.save_handoff(CW, 'x1\nx2\nx3\nx4', now=t0 + 120 + i)
ok('handoff <= 30 lines', len(open(p).read().splitlines()) <= 30)
# 6 task switch
prev = ['fix the login bug in auth module', 'now the login form validation fails on auth']
ok('switch new task', T.task_switch('new task: write the quarterly sales email to customers', prev))
ok('switch short reply', not T.task_switch('yes ok continue', prev))
ok('switch same topic followup', not T.task_switch('also check the login auth module error handling again', prev))
ok('switch low overlap no cue', not T.task_switch('please summarize the weather forecast for tomorrow morning', prev))
ok('switch different project path', T.task_switch('look at ~/rishav-cv and update the summary section text', ['edit ~/EditSutra panel code for captions please now']))
ok('switch no history', not T.task_switch('new task: something totally different here now', []))
# 7 idle
ok('idle 5m ttl', '1.25' in T.idle_cost(100000, 400, 300) and 'Fresh chat' in T.idle_cost(100000, 400, 300) and '5 min' in T.idle_cost(100000, 400, 300))
ok('idle 1h ttl', '2x' in T.idle_cost(100000, 4000, 3600) and '1 h' in T.idle_cost(100000, 4000, 3600))
ok('idle within ttl silent', T.idle_cost(100000, 3000, 3600) == '')
ok('idle short gap silent', T.idle_cost(100000, 200, 100) == '')
# 8 home
H2 = tempfile.mkdtemp(); os.makedirs(os.path.join(H2, 'old', '.git')); os.makedirs(os.path.join(H2, 'new'))
open(os.path.join(H2, 'new', 'HANDOFF.md'), 'w').write('x'); os.makedirs(os.path.join(H2, 'plain'))
os.utime(os.path.join(H2, 'old'), (1000, 1000))
ok('home suggests newest', 'cd ~/new' in T.home_cwd(H2, H2))
ok('home not in home silent', T.home_cwd(os.path.join(H2, 'old'), H2) == '')
ok('home no projects silent', T.home_cwd(tempfile.mkdtemp(), tempfile.mkdtemp()) == '')
# 9 paste
ok('paste big', 'every later call' in T.paste_warn('x' * 9000))
ok('paste small silent', T.paste_warn('x' * 100) == '')
ok('paste n param', T.paste_warn('x' * 100, n=50) != '')
# 10 defaults
pl = T.defaults_plan({}, {})
ok('defaults plan', ('model', None, 'sonnet') in pl and ('env.CLAUDE_CODE_SUBAGENT_MODEL', None, 'haiku') in pl)
ok('defaults autocompact missing note', any(k == 'MISSING' for k, _, _ in pl) and not any('AUTOCOMPACT' in k for k, _, _ in pl))
pl2 = T.defaults_plan({'model': 'opus'}, {'CLAUDE_AUTOCOMPACT_PCT_OVERRIDE': True})
ok('defaults keeps model, adds autocompact', not any(k == 'model' for k, _, _ in pl2) and any('AUTOCOMPACT' in k for k, _, _ in pl2))
sp = os.path.join(H, 'settings.json'); orig = {'model': 'opus', 'env': {'KEEP': '1', 'CLAUDE_CODE_SUBAGENT_MODEL': 'sonnet'}, 'x': [1]}
json.dump(orig, open(sp, 'w')); bd = os.path.join(H, 'dbk')
ch = T.defaults_plan(orig, {'CLAUDE_AUTOCOMPACT_PCT_OVERRIDE': True})
ap = T.apply_defaults(sp, ch, bd); s = json.load(open(sp))
ok('defaults applied', s['env']['CLAUDE_CODE_SUBAGENT_MODEL'] == 'haiku' and s['env']['CLAUDE_AUTOCOMPACT_PCT_OVERRIDE'] == '50' and s['model'] == 'opus' and len(ap) == 2)
T.restore_defaults(sp, bd)
ok('defaults restore exact', json.load(open(sp)) == orig)
json.dump({'a': 1}, open(sp, 'w')); ch = T.defaults_plan({'a': 1}, {}); T.apply_defaults(sp, ch, bd)
ok('defaults added model', json.load(open(sp))['model'] == 'sonnet')
T.restore_defaults(sp, bd)
ok('defaults restore removes added keys', json.load(open(sp)) == {'a': 1})
# 11 mcp
TD = tempfile.mkdtemp(); tps = []
for i in range(5):
    p = os.path.join(TD, 's%d.jsonl' % i); open(p, 'w').write(json.dumps({'message': {'content': [{'type': 'tool_use', 'name': 'mcp__used__go' if i == 2 else 'Read'}]}}) + '\n')
    os.utime(p, (1000 + i, 1000 + i)); tps.append(p)
res = T.mcp_unused(tps, ['used', 'idle'], 5)
ok('mcp unused found', res['unused'] == ['idle'])
ok('mcp advice park syntax', 'tz ondemand off idle' in res['advice'] and 'tz ondemand on' in res['advice'])
ok('mcp too few sessions silent', T.mcp_unused(tps[:2], ['idle'], 5)['advice'] == '')
ok('mcp prefix not confused', T.mcp_unused(tps, ['use'], 5)['unused'] == ['use'])
# 12 breakdown
tr = os.path.join(TD, 't.jsonl'); open(tr, 'w').write(json.dumps({'message': {'usage': {'input_tokens': 10, 'cache_read_input_tokens': 20000, 'cache_creation_input_tokens': 500}}}) + '\n')
b = T.context_breakdown(tr, H, CW)
ok('breakdown messages', isinstance(b['messages'], int) and b['messages'] > 0 and b['tools'] == 'UNKNOWN')
ok('breakdown render', T.render_breakdown(b).endswith('Exact numbers: /context (breakdown), /cost (session cost), /usage (plan limits).') and '[est]' in T.render_breakdown(b))
ok('breakdown missing file', T.context_breakdown('/nope', H, CW)['messages'] == 'UNKNOWN')
done()
